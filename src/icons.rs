//! 线性图标库
//!
//! 对应 UI 设计稿 v2 第 2.5 节：1.6px 线性图标、24px 网格、
//! `stroke-linecap/linejoin: round`、无填充。
//!
//! # 为什么不用 emoji
//! emoji 在 egui 里依赖系统 emoji 字体，Windows 与 macOS 的字形、基线、宽度都
//! 不一致，导航条会错位（设计稿 01 节第 6 条 + 8.1 节 P0）。这里全部改用
//! `painter` 画路径，跨平台像素一致。
//!
//! # 用法
//! ```ignore
//! icons::show(ui, icons::Icon::Home, 20.0, theme::TEXT_2);
//! ```

use eframe::egui;

/// 图标定义：24×24 网格下的折线 / 闭合多边形 / 圆 / 椭圆
struct Def {
    /// 开放折线
    open: &'static [&'static [(f32, f32)]],
    /// 闭合多边形
    closed: &'static [&'static [(f32, f32)]],
    /// 圆 (cx, cy, r)
    circles: &'static [(f32, f32, f32)],
    /// 椭圆 (cx, cy, rx, ry)
    ellipses: &'static [(f32, f32, f32, f32)],
}

const NONE: Def = Def {
    open: &[],
    closed: &[],
    circles: &[],
    ellipses: &[],
};

