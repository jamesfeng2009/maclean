/// 把图标画进给定矩形
pub fn paint(painter: &egui::Painter, rect: egui::Rect, ic: Icon, color: egui::Color32) {
    let d = ic.def();
    let s = rect.width() / 24.0;
    if s <= 0.0 {
        return;
    }
    // 设计稿：1.6px @ 24 网格；小尺寸下保底 1.4px，否则 16px 时细到看不见
    let stroke = egui::Stroke::new((1.6 * s).max(1.4), color);
    let o = rect.min;
    let p = |x: f32, y: f32| egui::pos2(o.x + x * s, o.y + y * s);

    for line in d.open {
        if line.len() < 2 {
            continue;
        }
        let pts: Vec<egui::Pos2> = line.iter().map(|&(x, y)| p(x, y)).collect();
        painter.add(egui::Shape::line(pts, stroke));
    }
    for poly in d.closed {
        if poly.len() < 3 {
            continue;
        }
        let pts: Vec<egui::Pos2> = poly.iter().map(|&(x, y)| p(x, y)).collect();
        painter.add(egui::Shape::closed_line(pts, stroke));
    }
    for &(cx, cy, r) in d.circles {
        painter.circle_stroke(p(cx, cy), (r * s).max(0.5), stroke);
    }
    for &(cx, cy, rx, ry) in d.ellipses {
        painter.add(egui::Shape::Ellipse(egui::epaint::EllipseShape {
            center: p(cx, cy),
            radius: egui::vec2(rx * s, ry * s),
            fill: egui::Color32::TRANSPARENT,
            stroke,
        }));
    }
}

/// 在 UI 中放置一个图标，占位 size×size
pub fn show(ui: &mut egui::Ui, ic: Icon, size: f32, color: egui::Color32) -> egui::Response {
    let (rect, response) = ui.allocate_exact_size(egui::vec2(size, size), egui::Sense::hover());
    if ui.is_rect_visible(rect) {
        paint(ui.painter(), rect, ic, color);
    }
    response
}

